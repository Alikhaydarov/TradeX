/**
 * Paints the mark on a canvas with its top-left at (x, y), scaled to `size`.
 *
 * Canvas has no SVG renderer, but Path2D takes the same path syntax, so the
 * geometry above can be replayed directly under the SVG's own transforms.
 */
export function drawTradoxyMark(
  ctx: CanvasRenderingContext2D,
  x: number,
  y: number,
  size: number,
  color: string,
) {
  const t = TRADOXY_MARK_TRANSFORM;
  ctx.save();
  ctx.translate(x, y);
  ctx.scale(size / TRADOXY_MARK_SIZE, size / TRADOXY_MARK_SIZE);
  ctx.translate(t.offsetX, t.offsetY);
  ctx.translate(t.flipX, t.flipY);
  ctx.scale(t.scaleX, t.scaleY);
  ctx.fillStyle = color;
  for (const d of TRADOXY_MARK_PATHS) ctx.fill(new Path2D(d));
  ctx.restore();
}
